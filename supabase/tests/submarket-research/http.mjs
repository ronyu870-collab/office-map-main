import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createHmac, randomBytes } from 'node:crypto';
import { once } from 'node:events';
import { createServer, request } from 'node:http';
import { ADMIN, OWNER, VIEWER } from '../lease-change-history/database.mjs';

async function listen(server) {
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  return server.address().port;
}
async function freePort() {
  const probe = createServer();
  const port = await listen(probe);
  await new Promise((resolve, reject) => probe.close(error => error ? reject(error) : resolve()));
  return port;
}
async function waitFor(url, accepts, child) {
  for (let attempt = 0; attempt < 100; attempt++) {
    if (child.exitCode !== null) throw new Error(`Server exited before ${url}`);
    const response = await fetch(url, { signal: AbortSignal.timeout(1500) }).catch(() => null);
    if (response && accepts(response.status)) return;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  throw new Error(`Server failed its readiness check at ${url}`);
}

export async function verifySubmarketHttp(db, edition, source) {
  const sql = db.setup;
  const receiptMigration = await source('20261121105118_audit_2_query_and_session_governance.sql');
  await sql.query(receiptMigration.slice(receiptMigration.indexOf('create table public.audit_operation_receipts'), receiptMigration.indexOf('-- Auth trigger remains')));
  await sql.query(await source('20261121140949_fix_audit_export_role_check.sql'));
  const role = `research_probe_${randomBytes(6).toString('hex')}`;
  const password = randomBytes(24).toString('hex');
  const secret = randomBytes(32).toString('hex');
  await sql.query(`
    alter table public.buildings add column grade text default 'A';
    alter table public.user_roles add column email text, add column full_name text;
    create table public.building_metrics (
      id bigint generated by default as identity primary key, building_id uuid, record_year integer, record_quarter integer,
      total_area numeric, net_effective_rent numeric, vacant_area numeric, vacancy_rate numeric,
      is_draft boolean, is_locked boolean, updated_at timestamptz, created_at timestamptz, data_source text
    );
    grant select on public.user_roles, public.buildings, public.building_metrics to service_role;
    grant usage on schema public to anon, authenticated, service_role;
    create role ${role} login noinherit password '${password}';
    grant anon, authenticated, service_role to ${role};
  `);
  const sign = (role, subject) => {
    const part = value => Buffer.from(JSON.stringify(value)).toString('base64url');
    const jwt = `${part({ alg: 'HS256', typ: 'JWT' })}.${part({ role, sub: subject, exp: Math.floor(Date.now() / 1000) + 120 })}`;
    return `${jwt}.${createHmac('sha256', secret).update(jwt).digest('base64url')}`;
  };
  const testUsers = new Map([ADMIN, OWNER, VIEWER].map(user => [sign('authenticated', user), user]));
  const gatewayPort = await freePort();
  const nextPort = await freePort();
  const base = `http://127.0.0.1:${nextPort}/api/map/submarket`;
  const gatewayBase = `http://127.0.0.1:${gatewayPort}`;
  const serviceKey = sign('service_role', ADMIN);
  // Only the GoTrue user response is a fixture. PostgREST, SQL, the bundled
  // Next route, authorization, row effects and audit completion are real.
  const bridge = createServer((req, res) => {
    if (req.url === '/auth/v1/user') {
      const user = testUsers.get((req.headers.authorization ?? '').replace('Bearer ', ''));
      res.writeHead(user ? 200 : 401, { 'content-type': 'application/json' });
      res.end(JSON.stringify(user ? { id: user, email: 'synthetic@example.org', role: 'authenticated' } : { message: 'Invalid token' }));
      return;
    }
    if (!req.url?.startsWith('/rest/v1/')) { res.writeHead(404).end(); return; }
    const upstream = request(gatewayBase + req.url.slice('/rest/v1'.length),
      { method: req.method, headers: req.headers }, response => {
        res.writeHead(response.statusCode, response.headers);
        response.pipe(res);
      });
    upstream.on('error', () => { if (!res.headersSent) res.writeHead(502); res.end(); });
    req.pipe(upstream);
  });

  const bridgePort = await listen(bridge);
  const gateway = spawn(process.env.POSTGREST_PATH || 'postgrest', [], {
    env: { PATH: process.env.PATH, PGRST_DB_URI: `postgresql://${role}:${password}@127.0.0.1:${process.env.LEASE_TEST_PG_PORT}/${db.database}`,
      PGRST_DB_SCHEMAS: 'public', PGRST_DB_ANON_ROLE: 'anon', PGRST_JWT_SECRET: secret,
      PGRST_SERVER_HOST: '127.0.0.1', PGRST_SERVER_PORT: String(gatewayPort) },
    stdio: ['ignore', 'ignore', 'inherit'],
  });
  let next;
  try {
    await waitFor(gatewayBase, status => status === 200, gateway);
    next = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'start', '--hostname', '127.0.0.1', '--port', String(nextPort)], {
      env: { ...process.env, NEXT_PUBLIC_SUPABASE_URL: `http://127.0.0.1:${bridgePort}`, SUPABASE_SECRET_KEY: serviceKey, NEXT_TELEMETRY_DISABLED: '1' },
      stdio: ['ignore', 'ignore', 'inherit'],
    });
    await waitFor(base + '?submarket=CBD', status => status === 401, next);
    const [adminToken, editorToken, viewerToken] = testUsers.keys();
    const call = (market, token = adminToken, options = {}) => {
      const params = new URLSearchParams({ submarket: market, ...options.query });
      return fetch(base + '?' + params, {
        method: options.body ? 'PUT' : 'GET',
        headers: { authorization: 'Bearer ' + token, 'content-type': 'application/json', ...options.headers },
        ...(options.body ? { body: JSON.stringify(options.body) } : {}),
      });
    };
    const read = async (response, status = 200) => {
      const body = await response.json();
      assert.equal(response.status, status, JSON.stringify(body));
      return body;
    };

    assert.ok([401, 403].includes((await fetch(gatewayBase + '/map_submarket_research_versions')).status));
    for (const item of edition) {
      const response = await read(await call(item.market, viewerToken));
      assert.equal(response.profilePublished, true);
      assert.equal(response.profile.research?.market ?? null, item.market === 'CBD' ? null : item.market);
      assert.equal(response.draftProfile, undefined);
      assert.equal(response.trendError, false);
    }
    const cbd = edition.find(item => item.market === 'CBD');
    const before = (await read(await call('CBD'))).draftProfile;
    const legacy = { headline: '隔离库区域定位', overview: '区域概况', industries: '产业研究', transport: '轨道与道路', demographics: [], policies: [], insights: [] };
    const submit = { ...legacy, research: cbd, expectedUpdatedAt: before.updatedAt, publicationIntent: 'publish' };
    await read(await call('CBD', editorToken, { body: submit }), 403);
    await read(await call('CBD', viewerToken, { body: submit }), 403);
    await read(await call('CBD', adminToken, { body: submit, headers: { 'x-colliers-impersonate-user': VIEWER } }), 403);
    await read(await call('CBD', viewerToken, { query: { researchHistory: '0' } }), 403);
    await read(await call('CBD', adminToken, { body: { ...submit, research: { ...cbd, market: '金融街' } } }), 422);
    const wrongProject = { ...cbd.projects[0], buildingId: edition.find(item => item.market === '丽泽').projects[0].buildingId };
    await read(await call('CBD', adminToken, { body: { ...submit, research: { ...cbd, projects: [wrongProject] } } }), 422);
    const outcomes = await Promise.all([call('CBD', adminToken, { body: submit }), call('CBD', adminToken, { body: submit })]);
    assert.deepEqual(outcomes.map(response => response.status).sort(), [200, 409]);
    const published = await read(await call('CBD', viewerToken));
    assert.equal(published.profile.headline, cbd.positioning);
    assert.equal(published.profile.overview, '');
    assert.equal(published.profile.research.projects[0].buildingId, cbd.projects[0].buildingId);

    const history = await read(await call('CBD', adminToken, { query: { researchHistory: '0' } }));
    assert.equal(history.versions[0].research, null);
    await read(await call('CBD', adminToken, { body: { ...submit, research: history.versions[0].research,
      expectedUpdatedAt: published.profile.updatedAt } }));
    const restored = await read(await call('CBD', viewerToken));
    assert.equal(restored.profile.headline, legacy.headline);
    assert.equal(restored.profile.research, null);
    const audit = (await sql.query(`select user_id, new_values from audit_logs where user_id=$1
      and target_table='map_submarket_profiles' and details->>'operation'='publish_submarket_profile'
      and details->>'outcome'='success' order by id`, [ADMIN])).rows;
    assert.equal(audit.length, 2);
    assert.equal(audit[0].new_values.research.positioning, cbd.positioning);
    assert.equal(audit[1].new_values.research, null);
    console.log('Built Next.js HTTP + PostgREST: all 16 reads, role denial, publish, conflict, version restore and durable audit passed');
  } finally {
    next?.kill();
    gateway.kill();
    bridge.closeAllConnections();
    await new Promise(resolve => bridge.close(resolve));
    await Promise.all([next, gateway].filter(child => child && child.exitCode === null && child.signalCode === null)
      .map(child => once(child, 'exit')));
    await sql.query(`drop role ${role}`);
  }
}
