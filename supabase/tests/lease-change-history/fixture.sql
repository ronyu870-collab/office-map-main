-- Synthetic rows only. Columns used by the real form/service and audit trigger
-- match the target types; unrelated tables and auth session machinery are omitted.
create schema auth;
create schema private;
create function auth.uid() returns uuid language sql stable as $$
  select coalesce(
    nullif(current_setting('request.jwt.claim.sub', true), ''),
    nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub'
  )::uuid
$$;
create table public.user_roles (
  user_id uuid primary key, role text not null, chinese_name text
);
