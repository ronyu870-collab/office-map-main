  ('22222222-2222-4222-8222-222222222222', 'editor', 'Synthetic colleague'),
  ('33333333-3333-4333-8333-333333333333', 'admin', 'Synthetic admin'),
  ('44444444-4444-4444-8444-444444444444', 'viewer', 'Synthetic viewer');
create function private.is_admin() returns boolean language sql stable
security definer set search_path = '' as $$
  select exists (select 1 from public.user_roles where user_id=(select auth.uid()) and role='admin')
$$;
create table public.lease_transactions (
  id uuid primary key default gen_random_uuid(),
  company varchar, suspected_company_fullname varchar, enterprise_type varchar,
  industry varchar, sub_industry varchar, demand_type varchar,
  new_building varchar, sub_market varchar, district varchar,
  building_grade varchar, floor_info varchar, floor text,
  old_address varchar, old_sub_market varchar, old_district varchar,
  old_building_grade varchar, area_sqm numeric, face_rent numeric,
  lease_term_months numeric, fit_out_months numeric, rent_free_months numeric,
  effective_rent numeric, transaction_date date, transaction_year integer,
  transaction_quarter varchar, remarks text, data_source varchar,
  submitter_id varchar, submitter_name varchar,
  original_submitter_id varchar, original_submitter_name varchar,
  relocation_area_change text,
  is_face_rent_estimated boolean not null default false,
  is_effective_rent_estimated boolean not null default false,
  created_at timestamptz default now(), updated_at timestamptz default now()
);
create table public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id text not null, action_type text not null, details jsonb,
  created_at timestamptz not null default now(), request_source text,
  module text, target_table text, target_id text, target_name text,
  old_values jsonb, new_values jsonb, event_id text unique,
  occurred_at timestamptz not null default now()
);
alter table public.lease_transactions enable row level security;
alter table public.audit_logs enable row level security;
alter table public.user_roles enable row level security;
create policy "users read own role" on public.user_roles for select
to authenticated using (user_id=(select auth.uid()));
create policy "admins read audit logs" on public.audit_logs for select
to authenticated using ((select private.is_admin()));
grant usage on schema public, auth, private to authenticated;
grant select on public.user_roles, public.audit_logs to authenticated;
grant select, insert, update, delete on public.lease_transactions to authenticated;

