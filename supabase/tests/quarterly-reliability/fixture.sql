-- Same identity-fill semantics/timing as the existing application trigger.
create function private.fill_update_draft_identity_period() returns trigger
language plpgsql security definer set search_path = '' as $$ begin
  if NEW.user_id is null then NEW.user_id := auth.uid(); end if;
  if NEW.record_year is null then NEW.record_year := private.current_submission_year(); end if;
  if NEW.record_quarter is null then NEW.record_quarter := private.current_submission_quarter(); end if;
  return NEW;
end $$;
create trigger update_drafts_fill_identity_period
before insert or update on public.update_drafts
for each row execute function private.fill_update_draft_identity_period();
create function private.set_updated_at() returns trigger
language plpgsql set search_path = '' as $$ begin NEW.updated_at := now(); return NEW; end $$;
