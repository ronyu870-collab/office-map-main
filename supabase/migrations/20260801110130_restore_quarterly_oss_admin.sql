create or replace view public.view_latest_quarterly_submissions
with (security_invoker = true)
as
select *
from (
  select s.*, row_number() over (
    partition by s.building_id, s.record_year, s.record_quarter
    order by s.created_at desc
  ) as rn
  from public.quarterly_submissions s
) ranked
where rn = 1;

create or replace function public.get_quarterly_submission_summary(p_year integer, p_quarter integer)
returns table (user_id uuid, building_id uuid, created_at timestamptz)
language sql
stable
set search_path = ''
as $$
  select distinct on (s.user_id, s.building_id)
    s.user_id, s.building_id, s.created_at
  from public.quarterly_submissions s
  where s.record_year = p_year and s.record_quarter = p_quarter
  order by s.user_id, s.building_id, s.created_at desc;
$$;

create or replace function public.get_all_tables()
returns table (table_name text, table_comment text)
language sql
stable
set search_path = ''
as $$
  select c.relname::text,
         coalesce(obj_description(c.oid, 'pg_class'), '')::text
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind in ('r', 'p')
    and private.is_admin()
  order by c.relname;
$$;

create or replace function public.get_table_columns(target_table text)
returns table (
  column_name text,
  data_type text,
  column_default text,
  is_nullable text,
  column_comment text
)
language sql
stable
set search_path = ''
as $$
  select a.attname::text,
         pg_catalog.format_type(a.atttypid, a.atttypmod)::text,
         pg_catalog.pg_get_expr(d.adbin, d.adrelid)::text,
         case when a.attnotnull then 'NO' else 'YES' end::text,
         coalesce(pg_catalog.col_description(a.attrelid, a.attnum), '')::text
  from pg_catalog.pg_attribute a
  join pg_catalog.pg_class c on c.oid = a.attrelid
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  left join pg_catalog.pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where n.nspname = 'public'
    and c.relname = target_table
    and c.relkind in ('r', 'p')
    and a.attnum > 0
    and not a.attisdropped
    and private.is_admin()
  order by a.attnum;
$$;

create or replace function public.get_all_memo_tags()
returns table(tag text)
language sql
stable
set search_path = ''
as $$
  select distinct unnest(m.tags) as tag
  from public.memos m
  where array_length(m.tags, 1) > 0 and private.is_admin()
  order by tag;
$$;

create or replace function public.lock_quarter(p_year integer, p_quarter integer)
returns table(locked_count bigint)
language plpgsql
set search_path = ''
as $$
begin
  if not private.is_admin() then raise exception 'admin access required'; end if;
  return query
  with changed as (
    update public.building_metrics
       set is_locked = true, locked_at = now(), locked_by = auth.uid()
     where record_year = p_year and record_quarter = p_quarter
     returning 1
  ) select count(*) from changed;
end;
$$;

create or replace function public.unlock_quarter(p_year integer, p_quarter integer, p_reason text)
returns table(unlocked_count bigint)
language plpgsql
set search_path = ''
as $$
begin
  if not private.is_admin() then raise exception 'admin access required'; end if;
  if nullif(trim(p_reason), '') is null then raise exception 'unlock reason is required'; end if;
  return query
  with changed as (
    update public.building_metrics
       set is_locked = false, locked_at = null, locked_by = null
     where record_year = p_year and record_quarter = p_quarter
     returning 1
  ) select count(*) from changed;
end;
$$;

create or replace function public.unlock_row(p_id bigint)
returns void
language plpgsql
set search_path = ''
as $$
begin
  if not private.is_admin() then raise exception 'admin access required'; end if;
  update public.building_metrics set is_locked = false, locked_at = null, locked_by = null where id = p_id;
end;
$$;

