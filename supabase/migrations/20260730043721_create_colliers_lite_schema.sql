begin;

create extension if not exists pgcrypto;
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.buildings (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  submarket text,
  grade text,
  city text,
  district text,
  location_lng double precision,
  location_lat double precision,
  completion_year text,
  leed_certification text,
  owner text,
  property_management text,
  contact_phone text,
  leasable_area numeric,
  is_active boolean not null default true,
  notes text,
  sort_order integer not null default 0,
  system_entry_date timestamptz default now(),
  former_names jsonb default '[]'::jsonb,
  project_type text default 'stock',
  is_entered_market boolean default true
);

create table public.building_metrics (
  id bigint primary key generated by default as identity,
  created_at timestamptz not null default now(),
  building_id uuid not null references public.buildings(id) on delete cascade,
  total_area double precision,
  asking_rent double precision,
  management_fee double precision,
  face_rent double precision,
  rent_free_period double precision,
  net_effective_rent double precision,
  vacancy_rate double precision,
  vacant_area double precision,
  record_year integer not null,
  record_quarter integer not null check (record_quarter between 1 and 4),
  is_locked boolean default false,
  is_draft boolean default false,
  data_source text,
  locked_at timestamptz,
  locked_by uuid,
  rent_qoq_change numeric,
  rent_yoy_change numeric,
  vacant_area_qoq_change numeric,
  updated_at timestamptz default now(),
  unique (building_id, record_year, record_quarter)
);

create table public.lease_transactions (
  id uuid primary key default gen_random_uuid(),
  company varchar,
  suspected_company_fullname varchar,
  enterprise_type varchar,
  industry varchar,
  sub_industry varchar,
  demand_type varchar,
  new_building varchar,
  sub_market varchar,
  district varchar,
  building_grade varchar,
  floor_info varchar,
  old_address varchar,
  old_sub_market varchar,
  old_building_grade varchar,
  area_sqm numeric check (area_sqm is null or area_sqm >= 0),
  face_rent numeric check (face_rent is null or face_rent >= 0),
  lease_term_months numeric check (lease_term_months is null or lease_term_months >= 0),
  fit_out_months numeric check (fit_out_months is null or fit_out_months >= 0),
  rent_free_months numeric check (rent_free_months is null or rent_free_months >= 0),
  effective_rent numeric check (effective_rent is null or effective_rent >= 0),
  transaction_date date,
  transaction_year integer,
  transaction_quarter varchar,
  remarks text,
  data_source varchar default 'broker_submission',
  submitter_id varchar,
  submitter_name varchar,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  is_face_rent_estimated boolean not null default false,
  is_effective_rent_estimated boolean not null default false,
  relocation_area_change text,
  floor text,
  original_submitter_id varchar,
  original_submitter_name varchar,
  old_district varchar
);

create table public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'viewer' check (role in ('viewer', 'editor', 'admin')),
  created_at timestamptz not null default timezone('utc', now()),
  phone text,
  seq_no integer,
  chinese_name text,
  full_name text,
  gender text,
  title text,
  email text,
  internal_number text,
  session_id uuid
);

create table public.messages (
  id bigint primary key generated by default as identity,
  user_email text not null,
  user_name text,
  content text not null check (char_length(content) between 1 and 2000),
  created_at timestamptz not null default timezone('utc', now())
);

create table public.announcements (
  id bigint primary key generated by default as identity,
  content text not null check (char_length(content) between 1 and 2000),
  created_at timestamptz not null default timezone('utc', now())
);

create table public.notices (
  id uuid primary key default gen_random_uuid(),
  content text not null check (char_length(content) between 1 and 2000),
  is_active boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by text not null default ''
);

create table public.audit_logs (
  id bigint primary key generated by default as identity,
  user_id text not null,
  action_type text not null,
  details jsonb default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  ip_address text,
  user_agent text,
  request_source text default 'frontend',
  module text,
  page_url text,
  target_table text,
  target_id text,
  target_name text,
  old_values jsonb,
  new_values jsonb,
  duration_ms integer,
  error_message text,
  event_id text unique
);

create index buildings_active_name_idx
  on public.buildings (name)
  where is_active = true;
create index buildings_map_filter_idx
  on public.buildings (submarket, grade)
  where is_active = true;
create index building_metrics_quarter_idx
  on public.building_metrics (record_year desc, record_quarter desc, building_id);
create index lease_transactions_date_idx
  on public.lease_transactions (transaction_date desc);
create index lease_transactions_created_idx
  on public.lease_transactions (created_at desc);
create index lease_transactions_submitter_idx
  on public.lease_transactions (submitter_id);
create index messages_created_at_idx
  on public.messages (created_at desc);
create index notices_active_updated_idx
  on public.notices (updated_at)
  where is_active = true;
create index audit_logs_created_at_idx
  on public.audit_logs (created_at desc);
create index audit_logs_user_created_idx
  on public.audit_logs (user_id, created_at desc);

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_roles
    where user_id = (select auth.uid())
      and role = 'admin'
  );
$$;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.user_roles (user_id, role, email, full_name)
  values (
    new.id,
    'viewer',
    new.email,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email, ''), '@', 1))
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

create trigger building_metrics_set_updated_at
before update on public.building_metrics
for each row execute function private.set_updated_at();

create trigger lease_transactions_set_updated_at
before update on public.lease_transactions
for each row execute function private.set_updated_at();

create trigger notices_set_updated_at
before update on public.notices
for each row execute function private.set_updated_at();

create trigger auth_user_created_profile
after insert on auth.users
for each row execute function private.handle_new_user();

alter table public.buildings enable row level security;
alter table public.building_metrics enable row level security;
alter table public.lease_transactions enable row level security;
alter table public.user_roles enable row level security;
alter table public.messages enable row level security;
alter table public.announcements enable row level security;
alter table public.notices enable row level security;
alter table public.audit_logs enable row level security;

revoke all on public.buildings from anon, authenticated;
revoke all on public.building_metrics from anon, authenticated;
revoke all on public.lease_transactions from anon, authenticated;
revoke all on public.user_roles from anon, authenticated;
revoke all on public.messages from anon, authenticated;
revoke all on public.announcements from anon, authenticated;
revoke all on public.notices from anon, authenticated;
revoke all on public.audit_logs from anon, authenticated;

grant select on public.buildings to authenticated;
grant select on public.building_metrics to authenticated;
grant select, insert, update, delete on public.lease_transactions to authenticated;
grant select on public.user_roles to authenticated;
grant update (phone, session_id) on public.user_roles to authenticated;
grant select, insert on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;
grant select on public.announcements to authenticated;
grant select, insert, update, delete on public.notices to authenticated;
grant select on public.audit_logs to authenticated;
grant usage on schema private to authenticated;
grant execute on function private.is_admin() to authenticated;

create policy "authenticated users read buildings"
on public.buildings for select
to authenticated
using (true);

create policy "authenticated users read building metrics"
on public.building_metrics for select
to authenticated
using (true);

create policy "authenticated users read lease transactions"
on public.lease_transactions for select
to authenticated
using (true);

create policy "authenticated users insert own lease transactions"
on public.lease_transactions for insert
to authenticated
with check (
  (select auth.uid()) is not null
  and submitter_id = (select auth.uid())::text
  and data_source = 'broker_submission'
);

create policy "authenticated users update own lease transactions"
on public.lease_transactions for update
to authenticated
using (submitter_id = (select auth.uid())::text)
with check (
  submitter_id = (select auth.uid())::text
  and data_source = 'broker_submission'
);

create policy "authenticated users delete own lease transactions"
on public.lease_transactions for delete
to authenticated
using (submitter_id = (select auth.uid())::text);

create policy "users read their profile and admins read profiles"
on public.user_roles for select
to authenticated
using (
  user_id = (select auth.uid())
  or (select private.is_admin())
);

create policy "users update safe fields on their profile"
on public.user_roles for update
to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

create policy "authenticated users read messages"
on public.messages for select
to authenticated
using (true);

create policy "authenticated users post messages as themselves"
on public.messages for insert
to authenticated
with check (
  (select auth.uid()) is not null
  and user_email = (select auth.jwt() ->> 'email')
);

create policy "authenticated users read announcements"
on public.announcements for select
to authenticated
using (true);

create policy "authenticated users read notices"
on public.notices for select
to authenticated
using (true);

create policy "admins create notices"
on public.notices for insert
to authenticated
with check ((select private.is_admin()));

create policy "admins update notices"
on public.notices for update
to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

create policy "admins delete notices"
on public.notices for delete
to authenticated
using ((select private.is_admin()));

create policy "admins read audit logs"
on public.audit_logs for select
to authenticated
using ((select private.is_admin()));

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
    and not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'messages'
    )
  then
    alter publication supabase_realtime add table public.messages;
  end if;
end
$$;

commit;
