import assert from 'node:assert/strict';
import { clickWorkspaceAction } from './workspace-actions.mjs';

export async function verifyListReading(page,{width,base}) {
  const id='10000000-1111-4111-8111-111111111111';
  const stock=Array.from({length:62},(_,index)=>({id:index ? `list-${index}` : id,name:index ? `批量项目${String(index).padStart(2,'0')}` : '存量同ID · 北京国际商务总部与城市更新示范中心',grade:'A',submarket:'CBD',district:'朝阳区',completion_year:2009,leed_certification:null,owner:'北京国际商务资产与城市更新投资管理集团有限公司',property_management:'InternationalCommercialPropertyManagementAndBuildingServicesCompanyLimited',location_lng:116.46+index*.0001,location_lat:39.91,building_metrics:[{id:`list-metric-${index}`,building_id:index ? `list-${index}` : id,record_year:2026,record_quarter:3,net_effective_rent:146.16,vacancy_rate:.211,total_area:80000}]}));
  const future=[{id,name:'规划同ID · International Commercial Business Headquarters Tower',grade:'A',type:'办公',submarket:'CBD',district:'朝阳区',launch_year:2027,launch_quarter:'Q2',total_area:50000,location_lng:116.47,location_lat:39.92},{id:'pending-list',name:'待核实列表项目',status:'pending',type:'办公',submarket:'CBD',district:'朝阳区',location_lng:116.48,location_lat:39.93}];
  await page.route('**/api/map/data?*',route=>{
    const url=new URL(route.request().url());
    if(url.searchParams.get('mode')==='future')return route.fulfill({json:{future_supplies:future}});
    if(url.searchParams.get('mode')==='map')return route.fulfill({json:{buildings:stock,display_overrides:[]}});
    return route.fallback();
  });
  await page.goto(new URL('/map',base).href);
  await page.waitForFunction(()=>window.__workspaceMap?.getCenter());
  await page.getByRole('button',{name:'筛选',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.map-live-stats .map-metric-number')[2]?.textContent==='64');
  await page.getByRole('button',{name:'筛选',exact:true}).click();
  console.log('list reading',width,'data ready');
  await page.getByRole('button',{name:'项目列表',exact:true}).click();
  const list=page.getByRole('region',{name:'项目列表',exact:true});await list.waitFor();
  await list.locator('.workspace-list-name').filter({hasText:'存量同ID'}).waitFor();
  const expanded=width<640||width===844;
  if(expanded)await clickWorkspaceAction(page,'全屏阅读工作区');
  const capture=async name=>{
    await page.waitForFunction(()=>!document.querySelector('.map-workspace-layout [data-exiting]'));
    await page.screenshot({animations:'disabled',path:`/tmp/map-list-${name}-${width}.png`});
  };
  await list.getByRole('button',{name:'选择项目',exact:true}).click();
  for(const name of [stock[0].name,stock[1].name]){
    const checkbox=list.getByRole('checkbox',{name:'选择'+name,exact:true});await checkbox.focus();await page.keyboard.press('Space');
  }
  const query=list.getByRole('searchbox',{name:'搜索当前项目列表',exact:true});
  await query.fill('规划同ID');
  const group=list.getByRole('region',{name:'比较项目选择',exact:true});
  await group.getByText('其中 2 栋不在当前结果中。',{exact:true}).waitFor();
  await list.getByText('预计时间',{exact:true}).waitFor();
  assert.equal(await list.getByText('空置率',{exact:true}).count(),0);
  await capture('outside-selection');console.log('list reading',width,'comparison scope');
  const remove=group.getByRole('button',{name:'移除结果外已选项目',exact:true});await remove.focus();await page.keyboard.press('Enter');
  await group.getByText('已选 0 栋',{exact:true}).waitFor();
  const futureChoice=list.getByRole('checkbox',{name:'选择'+future[0].name,exact:true});await futureChoice.focus();await page.keyboard.press('Space');
  await group.getByText('已选 1 栋',{exact:true}).waitFor();
  await query.fill('');
  await list.getByRole('button',{name:'完成选择',exact:true}).click();
  await list.getByText('更多',{exact:true}).click();
  await page.getByRole('button',{name:'详情',exact:true}).click();
  await page.keyboard.press('Escape');
  const first=list.locator('.workspace-basic-card').filter({hasText:'存量同ID'});await first.waitFor();
  assert.equal(await first.locator('.workspace-rent-metric dd').textContent(),'146.2元/㎡/月');
  await first.getByText('未提供',{exact:true}).waitFor();
  assert.equal(await first.getByText('楼宇等级',{exact:true}).count(),0);
  await first.scrollIntoViewIfNeeded();await capture('stock-card');console.log('list reading',width,'stock card');
  await query.fill('规划同ID');
  const planned=list.locator('.workspace-basic-card');await planned.getByText('规划总体量',{exact:true}).waitFor();
  assert.match(await planned.innerText(),/50,000/);assert.match(await planned.innerText(),/2027.*Q2/);
  assert.doesNotMatch(await planned.innerText(),/2026Q3|入市年份|146\.2/);
  await planned.scrollIntoViewIfNeeded();await capture('future-card');
  await query.fill('待核实列表项目');
  await list.locator('.workspace-basic-card').getByText('待核实项目',{exact:true}).waitFor();
  assert.equal(await list.getByText('入市年份',{exact:true}).count(),0);
  await capture('pending-card');
  console.log('list reading',width,'future and pending cards');
  await query.fill('规划同ID');await planned.click();
  await page.getByRole('region',{name:future[0].name+'楼宇详情',exact:true}).waitFor();
  await page.getByRole('button',{name:'返回项目列表',exact:true}).click();
  await list.waitFor();assert.equal(await query.inputValue(),'规划同ID');
  await query.fill('');
  await list.locator('.workspace-basic-card[aria-current="true"]').waitFor();
  assert.equal(await list.locator('.workspace-basic-card[aria-current="true"]').count(),1);
  assert.match(await list.locator('.workspace-basic-card[aria-current="true"]').innerText(),/规划同ID/);
  const scroller=list.locator('.workspace-scroll');
  await scroller.hover();await page.mouse.wheel(0,50000);
  await page.waitForFunction(()=>document.querySelector('[aria-label="项目列表"] .workspace-scroll')?.scrollTop>500);
  const selected=list.locator('.workspace-basic-card[aria-current="true"]');await selected.scrollIntoViewIfNeeded();
  await page.waitForTimeout(100);
  const saved=await scroller.evaluate(el=>el.scrollTop);
  await selected.click();await page.getByRole('region',{name:future[0].name+'楼宇详情',exact:true}).waitFor();
  await page.getByRole('button',{name:'返回项目列表',exact:true}).click();
  await list.waitFor();await page.waitForTimeout(250);
  const restored=await scroller.evaluate(el=>el.scrollTop);
  assert.ok(saved>500 && Math.abs(saved-restored)<3,`list scroll is retained rather than overridden by current identity: ${saved}/${restored}`);
  if(await page.locator('.map-workspace-layout[data-expanded]').count())await clickWorkspaceAction(page,'返回地图分屏');
  console.log('list reading',width,'restored scroll',saved,restored);
  const fullButton=page.getByRole('button',{name:'完整列表',exact:true});
  if(!await fullButton.isVisible())await page.locator('.map-header-navigation-mobile summary').click();
  await fullButton.click();
  const full=page.getByRole('region',{name:'完整楼宇列表',exact:true});await full.waitFor();
  const fullQuery=full.getByRole('searchbox');await fullQuery.fill('规划同ID');
  await full.getByRole('button',{name:'搜索',exact:true}).click();
  await full.getByText('规划总体量',{exact:true}).waitFor();
  assert.equal(await full.getByText('净有效租金',{exact:true}).count(),0);
  assert.match(await full.innerText(),/50,000\s*㎡/);
  await capture('full-future');
  return {width,planningCardOwnValues:true,stockRentOneDecimal:true,leedExplicitState:true,keyboardComparisonScope:true,removedOnlyOutsideSelection:true,selectionSurvivesListQuery:true,sameIdCurrentTypeUnique:true,retainedListScroll:{saved,restored},fullFutureAreaNamed:true};
}
